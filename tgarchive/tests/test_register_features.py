"""
Unit tests for L7 register/formality feature extraction.

Tests:
- Empty input returns defaults
- Messages without text return defaults
- JSON serializability of output
- Formality score comparison (formal vs informal register)
- Slang, profanity, and abbreviation detection and vocabularies
- Acronym and technical jargon rates
- Politeness markers, greetings, signoffs, and honorifics
- Direct address detection (@handles, pronouns)
- Colloquialisms and idiomatic expressions
- Scalar ranges and vocabulary capping
"""
from __future__ import annotations

import json
import pytest

from tgarchive.intelligence.features.register import (
    DEFAULT_REGISTER_FEATURES,
    extract_register_features,
)


class TestRegisterFeatures:
    """Tests for register and formality feature extraction."""

    def test_empty_messages(self):
        feat = extract_register_features([])
        assert isinstance(feat, dict)
        assert feat["formality_score"] == 0.0
        assert feat["slang_rate"] == 0.0
        assert feat["profanity_rate"] == 0.0
        assert feat["abbreviation_rate"] == 0.0
        assert feat["acronym_rate"] == 0.0
        assert feat["technical_jargon_rate"] == 0.0
        assert feat["colloquialism_rate"] == 0.0
        assert feat["idiom_rate"] == 0.0
        assert feat["politeness_marker_rate"] == 0.0
        assert feat["greeting_rate"] == 0.0
        assert feat["signoff_rate"] == 0.0
        assert feat["honorific_rate"] == 0.0
        assert feat["direct_address_rate"] == 0.0
        assert feat["profanity_vocabulary"] == {}
        assert feat["slang_vocabulary"] == {}
        assert feat["abbreviation_vocabulary"] == {}

    def test_messages_without_text(self):
        feat = extract_register_features([
            {"id": 10},
            {"content": None},
            {"text": ""},
        ])
        assert feat["formality_score"] == 0.0
        assert feat["slang_rate"] == 0.0

    def test_json_serializable(self):
        messages = [
            {
                "content": (
                    "Good morning Dr. Watson, please find the comprehensive vulnerability "
                    "analysis report for the Linux kernel subsystem. Sincerely."
                )
            }
        ]
        feat = extract_register_features(messages)
        serialized = json.dumps(feat)
        assert isinstance(serialized, str)
        deserialized = json.loads(serialized)
        assert deserialized["formality_score"] > 0.0
        assert deserialized["honorific_rate"] > 0.0

    def test_formal_vs_informal_comparison(self):
        formal_messages = [
            {
                "content": (
                    "Dear Dr. Harrison, with respect to the cryptographic protocol "
                    "implementation, we have completed the comprehensive mathematical "
                    "verification of the authentication handshake. Please find the "
                    "formal documentation attached. Best regards, Officer Vance."
                )
            }
        ]
        informal_messages = [
            {
                "content": (
                    "yo bruh wtf this is lit af lmao ngl rip that shit fam. "
                    "dude gonna get rekt noob sus vibes deadass."
                )
            }
        ]

        feat_formal = extract_register_features(formal_messages)
        feat_informal = extract_register_features(informal_messages)

        assert feat_formal["formality_score"] > feat_informal["formality_score"]
        assert feat_formal["formality_score"] >= 0.5
        assert feat_informal["formality_score"] <= 0.4

        assert feat_formal["slang_rate"] == 0.0
        assert feat_formal["profanity_rate"] == 0.0
        assert feat_informal["slang_rate"] > 0.0
        assert feat_informal["profanity_rate"] > 0.0
        assert feat_informal["abbreviation_rate"] > 0.0

    def test_slang_profanity_and_abbrev_vocabularies(self):
        messages = [
            {
                "content": (
                    "bruh tbh this shit is cringe af, lmao idk why he did that damn bug. "
                    "yeet it out fam."
                )
            }
        ]
        feat = extract_register_features(messages)
        assert "bruh" in feat["slang_vocabulary"] or "cringe" in feat["slang_vocabulary"]
        assert "shit" in feat["profanity_vocabulary"] or "damn" in feat["profanity_vocabulary"]
        assert "tbh" in feat["abbreviation_vocabulary"] or "lmao" in feat["abbreviation_vocabulary"]

    def test_technical_jargon_and_acronyms(self):
        messages = [
            {
                "content": (
                    "The Linux kernel compiler generated bytecode and bytecode deserialization "
                    "routines. The payload uses TCP and UDP to bypass the proxy."
                )
            }
        ]
        feat = extract_register_features(messages)
        assert feat["technical_jargon_rate"] > 0.0
        assert feat["acronym_rate"] > 0.0

    def test_greetings_signoffs_politeness_honorifics(self):
        messages = [
            {
                "content": (
                    "Hello team, please check the system logs. "
                    "Thank you for your assistance. Dr. Smith sent his best regards."
                )
            }
        ]
        feat = extract_register_features(messages)
        assert feat["greeting_rate"] > 0.0
        assert feat["politeness_marker_rate"] > 0.0
        assert feat["signoff_rate"] > 0.0
        assert feat["honorific_rate"] > 0.0

    def test_direct_address(self):
        messages = [
            {
                "content": "Hey @sec_lead and @dev_admin, you need to verify your credentials."
            }
        ]
        feat = extract_register_features(messages)
        assert feat["direct_address_rate"] > 0.0

    def test_colloquialisms_and_idioms(self):
        messages = [
            {
                "content": (
                    "It's a piece of cake to bite the bullet and hang out. "
                    "We are gonna chill and check it out."
                )
            }
        ]
        feat = extract_register_features(messages)
        assert feat["idiom_rate"] > 0.0
        assert feat["colloquialism_rate"] > 0.0

    def test_scalars_valid_and_vocabularies_capped(self):
        messages = [
            {
                "content": (
                    f"Message {i}: bruh wtf shit lit {i} @user_{i} "
                    f"please check kernel crypto API v{i}."
                )
            }
            for i in range(30)
        ]
        feat = extract_register_features(messages)
        assert 0.0 <= feat["formality_score"] <= 1.0
        assert 0.0 <= feat["slang_rate"] <= 1.0
        assert 0.0 <= feat["profanity_rate"] <= 1.0
        assert 0.0 <= feat["abbreviation_rate"] <= 1.0
        assert 0.0 <= feat["acronym_rate"] <= 1.0
        assert 0.0 <= feat["technical_jargon_rate"] <= 1.0
        assert 0.0 <= feat["colloquialism_rate"] <= 1.0
        assert 0.0 <= feat["idiom_rate"] <= 1.0
        assert 0.0 <= feat["politeness_marker_rate"] <= 1.0
        assert 0.0 <= feat["greeting_rate"] <= 1.0
        assert 0.0 <= feat["signoff_rate"] <= 1.0
        assert 0.0 <= feat["honorific_rate"] <= 1.0
        assert 0.0 <= feat["direct_address_rate"] <= 1.0

        assert len(feat["profanity_vocabulary"]) <= 50
        assert len(feat["slang_vocabulary"]) <= 50
        assert len(feat["abbreviation_vocabulary"]) <= 50
